UI_TEXT_JA = {value: key for key, value in UI_TEXT_EN.items()}

STATE_TEXT_EN = {
    "表示中": "Displaying",
    "対象外": "Skipped",
    "処理済み": "Processed",
    "処理中": "Processing",
    "処理対象外": "Skipped",
}


def translate_ui_text(text: str, language: str) -> str:
    if language == "en":
        return UI_TEXT_EN.get(text, text)
    return UI_TEXT_JA.get(text, text)


def translate_binding_text(text: str, language: str) -> str:
    mapping = UI_TEXT_EN if language == "en" else UI_TEXT_JA
    for source, target in mapping.items():
        text = text.replace(source, target)
    return text


def translate_state_text(state: str, language: str) -> str:
    if language != "en":
        return state
    return STATE_TEXT_EN.get(state, state.replace("待ち", " waiting"))
